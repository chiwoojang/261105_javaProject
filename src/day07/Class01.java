package day07;

public class Class01 {
	
	// ==> 메서드 선언 가능위치
	/* 두 정수를 받아(매개변수) 합을 리턴하는 메서드
	 * 리턴타입 : 합 (정수)
	 * 메서드명 : sum
	 * 매개변수 : 두 정수 (변수만 선언)
	 * */
	
	public int sum(int a,int b) {
		return a+b;
	}
	
	/* 두 정수를 입력받아(매개변수) 차를 리턴하는 메서드
	 * 리턴타입 : 차 (정수) => int
	 * 메서드명 : sub
	 * 매개변수 : 두 정수 => int a, int b
	 * */
	public int sub(int a, int b) {
		return a-b;
	}
	
	// 메서드 호출
	public static void main(String[] args) {
		int num1 = 1;
		int num2 = 2;
		
		// 같은 클래스 안에서 메서드를 호출 : 메스드명을 이용하여 호출
		// static : 일반 메서드 호출 불가 (static이 붙은 메서드만 호출가능)
		//  - 같은 클래스라도 객체를 생성해야 호출 가능.
		// 일반 메ㅐ서드는 객체 생성없이 호출가능 (같은 클래스라면....)
		
		// 다른 클래스는 반드시 객체를 생성해야 가능.
		
		// 클래스명 객체명 = new 클래스명();
		Class01 c = new Class01();
		int sum = c.sum(num1, num2);
		System.out.println(sum);
		int sub = c.sub(num1, num2);
		System.out.println(sub);
		
	}
	
	// 클래스  : 멤버변수(가지는 요소), 메서드(해야하는 기능)
	// main method : 컴파일러가 길행을 위해 제일 먼저 찾는 메서드
	
	 
	// 멤버변수의 위치 : 클래스 안 && 메서드 밖

	// 메서드의 위치 : 멤버변수 다음 (무순서) : 호출 => 실행
	
	/* 메서드 구조
	 * 접근제어자 리턴타입 메서드명(매개변수){
	 * 	구현;
	 *  return 변수명;  // 가장 마지막 , 있을 수도 있고, 없을 수도 있다.
	 *  // return의 변수명은 반드시 메서드의 리턴타입과 일치해야 함
	 * } 
	 * 
	 * 접근제어자 : 접근할 수 있는 주체의 제한범위
	 * public(누구나 접근) - 메서드
	 * default (같은 패키지)
	 * protected (같은 패키지 + 상속) - 상속을 염두
	 * private (나) - 멤버변수
	 * 
	 * 
	 * 리턴타입 : 메서드가 종료되고 난 후(처리가 완료되고 난 후) 반환 값 => 1개
	 * 	- void : 리턴할 값이 없다.
	 * 
	 *  메서드명 : 소문자로 시작(여러 의미를 붙여서 사용하 ㄹ경우 카멜케이스를 사용)
	 *  매개변수 : 파라미터 이 기능을 실행하기 위해 외부에서 받는 값
	 *   - 여러개 가능, 없어도 가능
	 *   - ()는 꼭 있어야 함.
	 *   
	 * return : 메서드를 종료하는 키워드  (void 의 경우는 return만 씀 -> 함수 종료)
	 *   - 리턴타입과 일치하는 리턴값을 주고 종료
	 *   - void는 없음   
	 *   
	 *   
	 * 메서드는 중복 선언이 암됨.
	 * 머서드 안에 또 다른 메서드가 있을 수 없음.
	 * 메서드 단위로 위치는 상관 없음
	 * 메서드 선언 위치
	 *  - 클래스 안, 다른 메서드 밖
	 *  - 메서드는 독립적 운영
	 *  - 순서는 상관없음
	 *  - 호출이 되어야 실행  
	 * */
	
}
